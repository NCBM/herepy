"""Classes from HerePy that cannot be loaded in Python.

The classes are set in java via inject().
"""

# pyright: reportUnusedParameter=hint

from collections.abc import Callable
from typing import TYPE_CHECKING, Any

from java.lang import Object
from java.lang.reflect import Type

if TYPE_CHECKING:
    from .typedefs import JepInterpreter

    class ReflectWrapper:
        class ReflectClass:
            def __init__(self, cls: type[Object] | Object) -> None: ...
            def getName(self) -> str: ...
            def getSimpleName(self) -> str: ...
            def getCanonicalName(self) -> str: ...
            def getPackageName(self) -> str: ...
            def getSuperclass(self) -> "ReflectWrapper.ReflectClass | None": ...
            def getInterfaces(self) -> list["ReflectWrapper.ReflectClass"]: ...
            def getMethods(self) -> list["ReflectWrapper.ReflectMethod"]: ...
            def getFields(self) -> list["ReflectWrapper.ReflectField"]: ...
            def getConstructors(self) -> list["ReflectWrapper.ReflectConstructor"]: ...
            def getTypeParameters(self) -> list["ReflectWrapper.ReflectTypeVariable"]: ...
            def getInnerClasses(self) -> list["ReflectWrapper.ReflectClass"]: ...
            def getModifiers(self) -> int: ...
            def isInterface(self) -> bool: ...
            def isEnum(self) -> bool: ...
            def isAbstract(self) -> bool: ...
            def isFinal(self) -> bool: ...
            def isAnnotation(self) -> bool: ...
            def getGenericSuperclass(self) -> "ReflectWrapper.ReflectType | None": ...
            def getGenericInterfaces(self) -> list["ReflectWrapper.ReflectType"]: ...
            def getRawClass(self) -> type[Object]: ...

        class ReflectMethod:
            def getName(self) -> str: ...
            def getDescriptor(self) -> str: ...
            def getModifiers(self) -> int: ...
            def isStatic(self) -> bool: ...
            def isFinal(self) -> bool: ...
            def isAbstract(self) -> bool: ...
            def isDefault(self) -> bool: ...
            def isVarArgs(self) -> bool: ...
            def isSynchronized(self) -> bool: ...
            def getReturnType(self) -> "ReflectWrapper.ReflectType": ...
            def getParameters(self) -> list["ReflectWrapper.ReflectParameter"]: ...
            def getTypeParameters(self) -> list["ReflectWrapper.ReflectTypeVariable"]: ...

        class ReflectField:
            def getName(self) -> str: ...
            def getModifiers(self) -> int: ...
            def isStatic(self) -> bool: ...
            def isFinal(self) -> bool: ...
            def getGenericType(self) -> "ReflectWrapper.ReflectType": ...

        class ReflectConstructor:
            def getDescriptor(self) -> str: ...
            def getModifiers(self) -> int: ...
            def isVarArgs(self) -> bool: ...
            def getParameters(self) -> list["ReflectWrapper.ReflectParameter"]: ...
            def getTypeParameters(self) -> list["ReflectWrapper.ReflectTypeVariable"]: ...

        class ReflectParameter:
            def getName(self) -> str: ...
            def isNamePresent(self) -> bool: ...
            def isVarArg(self) -> bool: ...
            def getType(self) -> "ReflectWrapper.ReflectType": ...

        class ReflectTypeVariable:
            def getName(self) -> str: ...
            def getBounds(self) -> list["ReflectWrapper.ReflectType"]: ...

        class ReflectType:
            def __init__(self, cls: type[Type] | Type) -> None: ...
            def getTypeName(self) -> str: ...
            def getCanonicalName(self) -> str: ...
            def isClass(self) -> bool: ...
            def isParameterized(self) -> bool: ...
            def isTypeVariable(self) -> bool: ...
            def isArray(self) -> bool: ...
            def isWildcard(self) -> bool: ...
            def isPrimitive(self) -> bool: ...
            def isVoid(self) -> bool: ...
            def getRawType(self) -> "ReflectWrapper.ReflectType": ...
            def getActualTypeArguments(self) -> list["ReflectWrapper.ReflectType"]: ...
            def getComponentType(self) -> "ReflectWrapper.ReflectType | None": ...
            def getArrayDimensions(self) -> int: ...
            def getUpperBounds(self) -> list["ReflectWrapper.ReflectType"]: ...
            def getLowerBounds(self) -> list["ReflectWrapper.ReflectType"]: ...

        @staticmethod
        def forClass(clz: type[Object]) -> "ReflectWrapper.ReflectClass": ...

        @staticmethod
        def forType(t: Type) -> "ReflectWrapper.ReflectType": ...

        @staticmethod
        def getLoadedClasses(classLoader: Any) -> list[type[Object]]: ...

    class PythonRunner:
        def __init__(self) -> None: ...

        def start(self, init: Callable[[JepInterpreter], None]) -> None: ...

        def submit(self, target: str, *args: object) -> None: ...

        def callSync(self, target: str, *args: object) -> object | None: ...

        def close(self) -> None: ...


def inject(name: str, val: object) -> None:
    globals()[name] = val
